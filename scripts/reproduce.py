"""Reproduce the benchmark results for one or more backbones.

Three levels, from cheapest to most expensive:

  evaluate  (CPU, minutes)  Re-run the evaluation on the released anomaly
                            scores in results/<model>/ -> metrics + plots.
  rescore   (GPU, hours)    Score val+test windows with the released LoRA
                            adapters in weights/<model>/, then evaluate.
  retrain   (GPU, longest)  Fine-tune each backbone from scratch on the
                            training windows, then score and evaluate.

Every run writes the exact config it used to outputs/<mode>/<model>/config.yaml.

Examples:
    uv run python scripts/reproduce.py --mode evaluate
    uv run python scripts/reproduce.py --mode rescore --models gemma-3-270m
    uv run python scripts/reproduce.py --mode retrain --models SmolLM2-135M
    uv run python scripts/reproduce.py --list
"""

from __future__ import annotations

import argparse
import copy
import subprocess
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MODEL_CONFIGS = ROOT / "configs" / "models"
SCRIPTS = ROOT / "scripts"
PROCESSED = "outputs/processed"

# Smallest -> largest.
SIZE_ORDER = [
    "SmolLM2-135M",
    "gemma-3-270m",
    "SmolLM2-360M",
    "Qwen2.5-0.5B",
    "Qwen2.5-1.5B",
    "gemma-3-1b-base",
    "SmolLM-1.7B",
    "SmolLM2-1.7B",
    "gemma-2-2b",
    "gemma-2-2b-base",
    "mistral-7b-v0.3",
    "Cosmos-Reason1-7B",
    "Qwen2.5-7B",
    "Qwen2.5-VL-7B-Instruct",
    "Llama-3.1-8B",
]


def available_models() -> list[str]:
    found = [p.stem for p in MODEL_CONFIGS.glob("*.yaml")]
    rank = {m: i for i, m in enumerate(SIZE_ORDER)}
    return sorted(found, key=lambda m: (rank.get(m, len(SIZE_ORDER)), m))


def write_run_config(model: str, mode: str) -> Path:
    """Derive the config for (model, mode) and save it under outputs/."""
    raw = yaml.safe_load((MODEL_CONFIGS / f"{model}.yaml").read_text(encoding="utf-8"))
    cfg = copy.deepcopy(raw)
    run_dir = f"outputs/{mode}/{model}"
    art = cfg["artifacts"]
    art["processed_dir"] = PROCESSED
    art["evaluation_dir"] = f"{run_dir}/evaluation"
    if mode == "evaluate":
        art["scores_dir"] = f"results/{model}"          # released scores
    elif mode == "rescore":
        art["model_dir"] = f"weights/{model}"           # released adapter
        art["scores_dir"] = f"{run_dir}/scores"
    elif mode == "retrain":
        art["model_dir"] = f"{run_dir}/model"           # freshly trained adapter
        art["scores_dir"] = f"{run_dir}/scores"
    path = ROOT / run_dir / "config.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"# Auto-generated by scripts/reproduce.py (mode={mode}) from configs/models/{model}.yaml\n"
    path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    return path


def run(step: str, script: str, args: list[str]) -> bool:
    print(f"  -> {step}", flush=True)
    start = time.time()
    ok = subprocess.call([sys.executable, str(SCRIPTS / script), *args], cwd=ROOT) == 0
    print(f"  <- {step} {'ok' if ok else 'FAILED'} ({(time.time() - start) / 60:.1f} min)", flush=True)
    return ok


def processed_ready() -> bool:
    d = ROOT / PROCESSED
    return all((d / f).is_file() for f in ("manifest.json", "train.npz", "val.npz", "test.npz"))


def require(path: Path, hint: str) -> str | None:
    return None if path.exists() else f"missing {path.relative_to(ROOT)} ({hint})"


def process_model(model: str, mode: str, force: bool) -> str:
    config = write_run_config(model, mode)
    cfg_arg = ["--config", str(config)]

    if mode == "evaluate":
        err = require(ROOT / "results" / model / "val_test_scores.npz", "released scores")
        if err:
            return err
    else:
        err = require(ROOT / "data" / "raw", "run scripts/download_assets.py --data")
        if err:
            return err
        if not processed_ready() and not run("preprocess", "preprocess.py", cfg_arg):
            return "preprocess failed"
        if mode == "rescore":
            err = require(
                ROOT / "weights" / model / "adapter" / "adapter_config.json",
                "run scripts/download_assets.py --weights",
            )
            if err:
                return err
        if mode == "retrain" and not run("train", "train.py", cfg_arg):
            return "training failed"
        score_args = [*cfg_arg, "--split", "all"] + (["--force"] if force else [])
        if not run("score", "score.py", score_args):
            return "scoring failed"

    if not run("evaluate", "evaluate.py", cfg_arg):
        return "evaluation failed"
    return "ok"


def main() -> None:
    models = available_models()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mode", choices=["evaluate", "rescore", "retrain"], default="evaluate")
    parser.add_argument("--models", nargs="+", metavar="NAME", help="Subset of backbones (default: all).")
    parser.add_argument("--force", action="store_true", help="Recompute scores instead of resuming.")
    parser.add_argument("--stop-on-error", action="store_true")
    parser.add_argument("--list", action="store_true", help="List backbones and exit.")
    args = parser.parse_args()

    if args.list:
        print("\n".join(models))
        return
    chosen = args.models or models
    unknown = sorted(set(chosen) - set(models))
    if unknown:
        parser.error(f"unknown model(s): {', '.join(unknown)}. Available: {', '.join(models)}")

    results: dict[str, str] = {}
    t0 = time.time()
    for i, model in enumerate(chosen, 1):
        print(f"\n=== [{i}/{len(chosen)}] {model} ({args.mode}) ===", flush=True)
        try:
            results[model] = process_model(model, args.mode, args.force)
        except KeyboardInterrupt:
            results[model] = "interrupted (re-run to resume scoring)"
            break
        if results[model] != "ok" and args.stop_on_error:
            break

    print(f"\n=== Summary ({(time.time() - t0) / 60:.1f} min) ===")
    for model in chosen:
        print(f"  {model:<20} {results.get(model, 'not run')}")
    print(f"Outputs: outputs/{args.mode}/<model>/evaluation/")
    sys.exit(0 if all(results.get(m) == "ok" for m in chosen) else 1)


if __name__ == "__main__":
    main()
